export function buildWordTimingsFromText(text: string, durationMs: number): WordTiming[] {
  const words = text.trim().split(/\s+/).filter(Boolean);
  if (words.length === 0) return [];
  const usable = Math.max(2000, durationMs - 400);
  const perWord = usable / words.length;
  return words.map((word, idx) => ({
    id: `w-${idx + 1}`,
    word,
    startMs: Math.round(200 + idx * perWord),
    endMs: Math.round(200 + (idx + 1) * perWord),
  }));
}

